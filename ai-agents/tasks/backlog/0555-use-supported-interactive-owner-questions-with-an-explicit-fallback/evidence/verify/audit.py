from pathlib import Path
import difflib
import hashlib
import json
import re
import subprocess
import sys

ROOT = Path.cwd()
TASK = Path('ai-agents/tasks/backlog/0555-use-supported-interactive-owner-questions-with-an-explicit-fallback')
BUILD = TASK / 'evidence/build'
VERIFY = TASK / 'evidence/verify'

def sha(path):
    return hashlib.sha256(Path(path).read_bytes()).hexdigest() if Path(path).is_file() else None

def hashes(paths):
    return {str(p): sha(p) for p in paths}

def dump(name, value):
    (VERIFY / name).write_text(json.dumps(value, indent=2, ensure_ascii=False) + '\n')

def counts(text):
    return {k: int(v) for k, v in re.findall(r'^[#ℹ] (tests|suites|pass|fail|cancelled|skipped|todo) (\d+)', text, re.M)}

phase = sys.argv[1]
baseline = json.loads((BUILD / 'baseline.json').read_text())
managed = json.loads((BUILD / 'managed-before.json').read_text())
build_hashes = hashes(sorted(p for p in BUILD.rglob('*') if p.is_file()))
inventory = subprocess.run(['git', 'ls-files', '--cached', '--others', '--exclude-standard'], capture_output=True, text=True, check=True).stdout.splitlines()
patch = subprocess.run(['git', 'diff', '--cached', '--binary'], capture_output=True, check=True).stdout
audit = {
    'provenance': 'Independently generated by Verify; not original Build final output',
    'phase': phase,
    'baselineSchema': {k: {'type': type(v).__name__, 'count': len(v) if isinstance(v, (list, dict)) else None} for k, v in baseline.items()},
    'sourceHashes': hashes(baseline['sourcePaths']),
    'sourceBeforeimageMismatches': [p for p, v in baseline['sourceHashes'].items() if sha(BUILD / 'before' / p) != v],
    'changedApprovedSources': [p for p, v in baseline['sourceHashes'].items() if sha(p) != v],
    'frozen0554Mismatches': [p for p, v in baseline['frozen0554'].items() if sha(p) != v],
    'recordMismatches': [p for p, v in baseline['records'].items() if sha(p) != v],
    'recordsCurrent': hashes(baseline['records']),
    'indexBaseline': baseline['indexSha256'],
    'indexCurrent': sha(baseline['indexPath']),
    'indexPatchBaseline': sha(BUILD / 'index-before.patch'),
    'indexPatchCurrent': hashlib.sha256(patch).hexdigest(),
    'workspaceBaselineDeltas': {p: {'baseline': v, 'current': sha(p)} for p, v in baseline['workspaceHashes'].items() if sha(p) != v},
    'workspaceInventoryAdditions': [p for p in inventory if p not in baseline['workspaceHashes']],
    'managedBeforeimageMismatches': [p for p, v in managed.items() if sha(BUILD / 'managed-before' / p) != v],
    'managedCurrentHashes': hashes(managed),
    'managedChangesSinceBuildBaseline': [p for p, v in managed.items() if sha(p) != v],
    'managedBlocks': {},
    'missingBuildHandoff': [str(p) for p in [TASK / 'worklog.md', BUILD / 'artifact-manifest.json', BUILD / 'task-source.diff'] if not p.exists()],
    'buildEvidenceHashes': build_hashes,
}
block = re.compile(rb'(?m)^<!-- fkit:begin-rules -->\n[\s\S]*?^<!-- fkit:end-rules -->\n?')
for p in ['CLAUDE.md', 'AGENTS.md']:
    current = Path(p).read_bytes()
    before = (BUILD / 'before' / p).read_bytes()
    b = block.search(current).group()
    audit['managedBlocks'][p] = {'bytes': len(b), 'freeBytesOf4352': 4352 - len(b), 'ownerBytesPreserved': block.sub(b'', current) == block.sub(b'', before)}
audit['askingConventionEqual'] = Path('claude/scaffold/ai-agents/knowledge-base/conventions/asking-the-owner.md').read_bytes() == Path('ai-agents/knowledge-base/conventions/asking-the-owner.md').read_bytes()
audit['deliveryCaptureBindings'] = {}
for lane in ['delivery', 'delivery-final', 'delivery-budget-corrected', 'delivery-complete']:
    records = json.loads((BUILD / (lane + '.stdout')).read_text())['records']
    bound = {}
    for record in records:
        if 'runtime' in record:
            p = BUILD / 'delivery' / f"{record['runtime']}-{record['label']}-instructions.txt"
            bound[str(p)] = sha(p) == record['instructionsSha256']
    audit['deliveryCaptureBindings'][lane] = bound
if phase == 'before':
    for p in baseline['sourcePaths']:
        out = VERIFY / 'current-source' / p
        out.parent.mkdir(parents=True, exist_ok=True)
        out.write_bytes(Path(p).read_bytes())
    diff = ''
    for p in baseline['sourcePaths']:
        before = (BUILD / 'before' / p).read_text().splitlines(True)
        after = Path(p).read_text().splitlines(True)
        diff += f'diff --git a/{p} b/{p}\n' + ''.join(difflib.unified_diff(before, after, fromfile='a/' + p, tofile='b/' + p))
    (VERIFY / 'task-source.diff').write_text(diff)
    dump('build-evidence-hashes.json', build_hashes)
    dump('source-hashes.json', audit['sourceHashes'])
    inherited = []
    for p in sorted(BUILD.glob('*.json')):
        if p.name in ['baseline.json', 'managed-before.json']:
            continue
        record = json.loads(p.read_text())
        stdout = p.with_suffix('.stdout')
        stderr = p.with_suffix('.stderr')
        inherited.append({'path': str(p), 'record': record, 'counts': counts(stdout.read_text()) if stdout.exists() else {}, 'stdoutSha256': sha(stdout), 'stderrSha256': sha(stderr)})
    dump('inherited-checks.json', inherited)
else:
    before = json.loads((VERIFY / 'audit-before.json').read_text())
    audit['preservedSinceVerifyStart'] = {
        'sources': audit['sourceHashes'] == before['sourceHashes'],
        'buildEvidence': build_hashes == before['buildEvidenceHashes'],
        'managedFiles': audit['managedCurrentHashes'] == before['managedCurrentHashes'],
        'records': audit['recordsCurrent'] == before['recordsCurrent'],
        'index': audit['indexCurrent'] == before['indexCurrent'],
        'workspaceAdditionalDeltas': [p for p in baseline['workspaceHashes'] if sha(p) != before['workspaceBaselineDeltas'].get(p, {}).get('current', baseline['workspaceHashes'][p])],
    }
dump('audit-' + phase + '.json', audit)
print(json.dumps({k: audit[k] for k in ['phase', 'sourceBeforeimageMismatches', 'frozen0554Mismatches', 'recordMismatches', 'indexCurrent', 'managedBeforeimageMismatches', 'managedBlocks', 'missingBuildHandoff']}, indent=2))
if phase != 'before':
    print(json.dumps(audit['preservedSinceVerifyStart'], indent=2))
