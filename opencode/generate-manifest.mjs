#!/usr/bin/env node
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { hashFor } from '../bin/generate-structure-manifest.mjs';
import { scaffoldContent } from './adapt.mjs';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const output = path.join(root, 'opencode/structure-manifest.tsv');
const entries = new Set();
// Keep previously shipped native hashes: discarding history would make safe stale repairs impossible.
for (const manifest of ['claude/structure-manifest.tsv', 'opencode/structure-manifest.tsv']) {
  const file = path.join(root, manifest);
  if (!fs.existsSync(file)) continue;
  for (const line of fs.readFileSync(file, 'utf8').split('\n')) {
    if (!/^[a-f0-9]{64}\t/.test(line)) continue;
    const rel = line.slice(65);
    if (rel !== 'CLAUDE.md') entries.add(line);
  }
}
function add(rel) {
  const text = fs.readFileSync(path.join(root, 'claude/scaffold', rel), 'utf8');
  entries.add(`${hashFor(rel, Buffer.from(scaffoldContent(rel, text)).toString('latin1'))}\t${rel}`);
}
function walk(rel) {
  for (const item of fs.readdirSync(path.join(root, 'claude/scaffold', rel), { withFileTypes: true })) {
    if (item.name === '.DS_Store' || item.name === '.gitkeep') continue;
    const child = path.posix.join(rel, item.name);
    if (item.isDirectory()) walk(child);
    else if (item.isFile()) add(child);
  }
}
add('AGENTS.md');
walk('ai-agents');
const lines = [...entries].sort((a, b) => a.slice(65).localeCompare(b.slice(65), 'en') || a.localeCompare(b, 'en'));
fs.writeFileSync(output, '# OpenCode scaffold hashes, including known Claude templates for migration.\n' +
  '# Generated by node opencode/generate-manifest.mjs; retain historical entries.\n' +
  '# Hash contract: CRLF -> LF; AGENTS.md elides only the managed marker interior; SHA-256.\n' + lines.join('\n') + '\n');
console.log(`Wrote opencode/structure-manifest.tsv (${lines.length} hashes)`);
